// تطبيع خفيف: التاجر يكتب "الفساتين " أو "أزياء نسائية" بألف مهموزة أو بدونها.
function normalizeCategory(category) {
  return String(category ?? "")
    .trim()
    .toLowerCase()
    .replace(/[ً-ْـ]/g, "") // تشكيل وتطويل
    .replace(/[إأآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/\s+/g, " ");
}

const NORMALIZED_ALIASES = new Map(
  [...ALIASES].map(([alias, key]) => [normalizeCategory(alias), key])
);

/**
 * كتيب المصطلحات الجاهز للحقن، أو `""` لفئة غير مغطاة (أو غائبة/تالفة).
 * `""` **ليس حالة خطأ** — هو التعاقد: بلا كتيب، يبقى التوجيه كما هو حرفياً.
 */
export function taxonomyForCategory(category) {
  const key = NORMALIZED_ALIASES.get(normalizeCategory(category));
  return key ? TAXONOMIES[key] : "";
}

/**
 * نفس الكتيب، لكن باسم المنتج كمصدر احتياطي حين تكون فئة المتجر غير مطابقة.
 *
 * سبب وجودها (مرصود بفيديو 2026-09-08): منتج اسمه "فستان" بمتجر التاجر
 * مصنَّف تحت فئة **"البلايز"**. فئة المتجر بيانات تاجر لا تصنيف موثوق —
 * وحين لا تُطابق، كان الكتيب كله يُسقَط بصمت والنموذج يسمّي من عنده. هذا
 * بالضبط ما رآه صاحب المشروع بالمخرج: وصف بلا "ماكسي" ولا "قصّة A".
 *
 * الاحتياط: **الكلمة الأولى من الاسم فقط**، لا بحث جزئي. البحث الجزئي يحقن
 * معجم الفساتين على "شنطة تناسب الفساتين" — وهو نفس التلوّث الذي أُغلقت
 * القائمة لمنعه. الكلمة الأولى تكفي: التجار يبدؤون الاسم بنوع المنتج
 * ("فستان سهرة أخضر"، "عباية كلوش")، وإن لم يفعلوا فالنتيجة `""` كما كانت.
 *
 * الفئة تبقى الأسبق دائماً — الاسم مصدر أضعف، لا بديل.
 */
export function taxonomyForProduct({ category, name } = {}) {
  const byCategory = taxonomyForCategory(category);
  if (byCategory) return byCategory;

  const firstWord = normalizeCategory(name).split(" ")[0];
  if (!firstWord) return "";
  const key = NORMALIZED_ALIASES.get(firstWord);
  return key ? TAXONOMIES[key] : "";
}
