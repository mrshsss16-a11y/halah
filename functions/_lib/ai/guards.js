/** @returns {{text:string, stripped:boolean, topic:string|null}} */
export function stripArchivedClaims(text) {
  const src = String(text ?? "");
  for (const { topic, re } of ARCHIVED_CLAIMS) {
    if (re.test(src)) return { text: ARCHIVED_CANONICAL[topic], stripped: true, topic };
  }
  return { text: src, stripped: false, topic: null };
}
