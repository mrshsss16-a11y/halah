/** فئة المعيار من الاسم أولاً ثم تصنيف المتجر. */
export function copyCategoryFor({ category = "", name = "" } = {}) {
  for (const text of [name, category]) {
    const hit = DETECT.find(([, re]) => re.test(String(text || "")));
    if (hit) return hit[0];
  }
  return "general";
}

export function decisionQuestionsBlock({ category = "", name = "" } = {}) {
  const key = copyCategoryFor({ category, name });
  return [
    `## أسئلة قرار الشراء لهذه الفئة (${key}) — معيار هالة`,
    "أجيبي في أول الوصف أو في النقاط أو جدول المواصفات عن كل سؤال له جواب في اسم المنتج أو بيانات التاجر أو الصورة.",
    "السؤال الذي لا جواب له في هذه المصادر يُترك تماماً: لا تخمين، ولا «حسب المتجر»، ولا إحالة.",
    ...QUESTIONS[key].map((q) => `- ${q}`)
  ].join("\n");
}
