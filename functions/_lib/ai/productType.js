export function categoryNameFor(type) {
  return CATEGORY_NAMES[type] || type;
}

/** تطبيع خفيف — نفس قواعد `productTaxonomy.js` ليتطابق السلوك. */
function normalize(text) {
  return String(text ?? "")
    .trim()
    .toLowerCase()
    .replace(/[ً-ْـ]/g, "")
    .replace(/[إأآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/\s+/g, " ");
}

const LOOKUP = new Map();
for (const [type, aliases] of Object.entries(TYPES)) {
  for (const alias of aliases) LOOKUP.set(normalize(alias), type);
}

export const KNOWN_TYPES = Object.keys(TYPES);

/**
 * نوع المنتج من **الكلمة الأولى** لنص (اسم منتج، أو أول جملة بملاحظات الصورة).
 * لا مطابقة ⇒ `null` — وهذا تعاقد لا حالة خطأ.
 */
export function productTypeOf(text) {
  const first = normalize(text).split(" ")[0];
  if (!first) return null;
  return LOOKUP.get(first) || null;
}

/**
 * نوع المنتج كما **تراه هالة**: ملاحظات الصورة أولاً (شهادة بصرية)، ثم اسم
 * المنتج. الفئة المسجّلة بالمتجر **ليست مصدراً هنا** عمداً — هي بالضبط ما
 * نفحص صحته.
 */
export function detectProductType({ visionNotes, name } = {}) {
  return productTypeOf(visionNotes) || productTypeOf(name) || null;
}

/**
 * هل تصنيف المتجر يخالف ما رأته هالة؟
 *
 * يرجّع `null` حين لا يوجد ما يُقال بيقين: نوع غير معروف أو تصنيف مطابق.
 * تعارض نوعين معروفين ⇒ `{ detected, current }` (تصحيح).
 * نوع معروف وتصنيف فارغ أو لا يدل على نوع («وصل حديثاً») ⇒ `{ detected, current: null, currentName }`
 * (اقتراح **إضافة** تصنيف نوع — التسويقي يبقى، 2026-09-14).
 *
 * @returns {{ detected: string, current: string|null, currentName?: string } | null}
 */
export function categoryMismatch({ visionNotes, name, category } = {}) {
  const detected = detectProductType({ visionNotes, name });
  if (!detected) return null;
  const currentType = productTypeOf(category);
  if (currentType === detected) return null;
  if (!currentType) return { detected, current: null, currentName: String(category ?? "").trim() };
  return { detected, current: currentType };
}
