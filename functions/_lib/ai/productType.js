// استنتاج **نوع المنتج** من قراءة الصورة — لتصحيح تصنيف خاطئ بالمتجر.
//
// المشكلة المرصودة (فيديو صاحب المشروع 2026-09-09): فستان مصنَّف بسلة تحت
// **«التنانير»**. هالة ترى الفستان بالصورة وتصفه فستاناً، ثم تسكت عن التصنيف
// الخاطئ. تصنيف خاطئ يضرب التصفح والفلترة والسيو داخل المتجر، وهو نفسه الذي
// كان يُسقط كتيب المصطلحات بصمت قبل أن يُضاف احتياط اسم المنتج.
//
// حدود صارمة، بنفس منطق `productTaxonomy.js`:
//   - **قائمة مغلقة**: لا يُستنتج نوع خارج الأنواع المعروفة. لا مطابقة ⇒ `null`.
//   - **الكلمة الأولى تحكم**: "فستان سهرة أخضر" ⇒ فستان. أما "شنطة تناسب
//     الفساتين" فكلمتها الأولى شنطة ⇒ لا استنتاج. البحث الجزئي هو بالضبط ما
//     أُغلقت القائمة لمنعه.
//   - **اقتراح لا تنفيذ**: المخرج يُعرض للتاجر ليقرر. تغيير تصنيف منتج على
//     متجر حي بلا موافقته تصرّف بمتجره، لا مساعدة.

/** الأنواع المعروفة ومرادفاتها كما تكتبها المتاجر السعودية فعلاً. */
const TYPES = {
  فستان: ["فستان", "فساتين", "الفستان", "الفساتين"],
  عباية: ["عباية", "عبايات", "العباية", "العبايات", "عبايه"],
  تنورة: ["تنورة", "تنانير", "التنورة", "التنانير", "تنوره", "جيبة"],
  بلوزة: ["بلوزة", "بلايز", "البلوزة", "البلايز", "بلوزه", "قميص", "قمصان"],
  بنطلون: ["بنطلون", "بناطيل", "البنطلون", "البناطيل", "بنطال"],
  جاكيت: ["جاكيت", "جاكيتات", "الجاكيت", "بليزر", "معطف"],
  طقم: ["طقم", "أطقم", "اطقم", "الطقم"],
  حذاء: ["حذاء", "أحذية", "احذية", "الحذاء", "شوز"],
  حقيبة: ["حقيبة", "حقائب", "الحقيبة", "شنطة", "شنط", "شنطه"],
  قلادة: ["قلادة", "قلادات", "سلسال", "سلاسل", "عقد"],
  خاتم: ["خاتم", "خواتم", "الخاتم", "دبلة"],
  أقراط: ["أقراط", "اقراط", "حلق", "حلقان"],
  سوار: ["سوار", "أساور", "اساور", "إسورة"],
  عطر: ["عطر", "عطور", "العطر", "برفان"]
};

/** تطبيع خفيف — نفس قواعد `productTaxonomy.js` ليتطابق السلوك. */
function normalize(text) {
  return String(text ?? "")
    .trim()
    .toLowerCase()
    .replace(/[ً-ْـ]/g, "")
    .replace(/[إأآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/\s+/g, " ");
}

const LOOKUP = new Map();
for (const [type, aliases] of Object.entries(TYPES)) {
  for (const alias of aliases) LOOKUP.set(normalize(alias), type);
}

export const KNOWN_TYPES = Object.keys(TYPES);

/**
 * نوع المنتج من **الكلمة الأولى** لنص (اسم منتج، أو أول جملة بملاحظات الصورة).
 * لا مطابقة ⇒ `null` — وهذا تعاقد لا حالة خطأ.
 */
export function productTypeOf(text) {
  const first = normalize(text).split(" ")[0];
  if (!first) return null;
  return LOOKUP.get(first) || null;
}

/**
 * نوع المنتج كما **تراه هالة**: ملاحظات الصورة أولاً (شهادة بصرية)، ثم اسم
 * المنتج. الفئة المسجّلة بالمتجر **ليست مصدراً هنا** عمداً — هي بالضبط ما
 * نفحص صحته.
 */
export function detectProductType({ visionNotes, name } = {}) {
  return productTypeOf(visionNotes) || productTypeOf(name) || null;
}

/**
 * هل تصنيف المتجر يخالف ما رأته هالة؟
 *
 * يرجّع `null` حين لا يوجد ما يُقال بيقين: نوع غير معروف، أو فئة فارغة، أو
 * فئة لا تُطابق أي نوع معروف (قد تكون تصنيفاً تسويقياً مشروعاً مثل «وصل
 * حديثاً» — ليست خطأً). التنبيه يخرج فقط حين **يتعارض نوعان معروفان**.
 *
 * @returns {{ detected: string, current: string } | null}
 */
export function categoryMismatch({ visionNotes, name, category } = {}) {
  const detected = detectProductType({ visionNotes, name });
  if (!detected) return null;
  const currentType = productTypeOf(category);
  if (!currentType || currentType === detected) return null;
  return { detected, current: currentType };
}
