// كشف الآلية وبنية بيانات المتجر، وصفات فارغة على التفاصيل — لكل حقل منشور (2026-09-15).
//
// صفحتان حقيقيتان بعد نشر copyOccasion.js: «يظهر التصميم باللون الرمادي في النموذج المعروض، وتتوافر التنورة
// بالرمادي والبنفسجي.» تصف صورة لا منتجاً (معيار ٦.٦، معجم «كشف الآلية» ٧.٥)، و«وبألوان المتجر المسجلة تحت
// الخيارات من 36 إلى 44» تصف بنية بيانات المتجر. يُحذف المقطع وحده وتبقى حقيقة التوفّر في بقية الجملة.
// و«سطحها مطفي ونقشتها منقوشة» تكرار لا يصف شيئاً، و«جيوب عملية» و«طبقات واضحة» حكم بلا مصدر على تفصيل:
// تُحذف الصفة ويبقى التفصيل.
import { splitSentencesKeep, joinSentences } from "./copyPhrases.js";
import { dropClauses } from "./copyJudgments.js";

const normAr = (t) => String(t || "").replace(/[ً-ْـ]/g, "").replace(/[أإآ]/g, "ا").replace(/ة/g, "ه").replace(/ى/g, "ي");

/** عبارات تصف الصورة المعروضة أو قائمة خيارات المتجر بدل المنتج. */
// معجم كشف الآلية (٧.٥) وُسِّع 2026-09-16: صفحة فعلية بأسئلة شائعة قالت «تتوفر التنورة باللونين الرمادي
// والبنفسجي. اللون الظاهر في …» — الجملة الأولى حقيقة توفّر تبقى، والجملة الثانية تصف الصورة فتُحذف كاملة.
// أُضيفت أيضاً «كما يظهر»، «يبدو»، «الإضاءة»، «الخلفية» (حين تصف مشهد التصوير لا نقشة القماش) و«نموذج المنتج»
// (نموذج «المعروض» كانت وحدها مغطاة). «الظاهر/ة/ين» مقيّدة بسياق صورة/نموذج كي لا تُسقط وصفاً ماديّاً حقيقياً
// كتيبة عن تفصيل ظاهر بالقطعة نفسها («الحزام الظاهر من الخصر» يبقى — لا صورة ولا نموذج بجواره).
export const MECHANISM_PHRASE = /(?<!\p{L})(?:(?:ال)?نموذج[ \t]+(?:ال)?معروض|(?:ال)?نموذج[ \t]+(?:ال)?منتج|في[ \t]+(?:ال)?نموذج|(?:و)?(?:ي|ت)ظهر[ \t]+(?:ال)?(?:تصميم|منتج|قطع(?:ة|ه))|كما[ \t]+(?:ي|ت)ظهر|(?:و)?يبدو(?:[ \t]+[أا]ن)?|(?:ال)?معروض(?:ة|ه)?[ \t]+(?:في|ب)[ \t]*(?:ال)?صور(?:ة|ه)|(?:ال)?قطع(?:ة|ه)[ \t]+(?:ال)?معروض(?:ة|ه)|(?:ال)?مسجل(?:ة|ه)?[ \t]+تحت[ \t]+(?:ال)?خيارات|تحت[ \t]+(?:ال)?خيارات|(?:و|ب|وب)?[أا]لوان[ \t]+(?:ال)?متجر|(?:ال)?لون[ \t]+(?:ال)?ظاهر(?:ة|ه|ين)?|(?:ال)?ظاهر(?:ة|ه|ين)?[ \t]+(?:في|ب)[ \t]*(?:ال)?(?:صور(?:ة|ه)|نموذج)|(?:ال)?[إا]ضاء(?:ة|ه)[ \t]+(?:في|ب|من)[ \t]*(?:ال)?(?:صور(?:ة|ه)|تصوير|لقط(?:ة|ه))|(?:ال)?خلفي(?:ة|ه)[ \t]+(?:في|من|بال)?(?:ال)?صور(?:ة|ه))(?!\p{L})/u;

/** يُحذف المقطع (بين الفواصل) الذي يصف الصورة أو بنية الخيارات، وتبقى بقية الجملة: «…المعروض، وتتوافر التنورة…» ⇒ «تتوافر التنورة…». */
export function dropMechanismClauses(text) {
  const t = String(text || "");
  if (!MECHANISM_PHRASE.test(t)) return t;
  return joinSentences(splitSentencesKeep(t).map(({ s, p }) => ({ p, s: dropClauses(s, (c) => MECHANISM_PHRASE.test(c)) })));
}

// «منقوش» قيمة نقشة عامة (visionFacts.js يبقيها بالمواصفات): «ونقشتها منقوشة»، «مع نقشة منقوشة» — تُحذف العبارة كلها.
const PATTERN_TAUTOLOGY = /[ \t]*،?[ \t]*(?<!\p{L})(?:و|ب|مع[ \t]+)?(?:ال)?(?:نقش(?:تها|ته|اتها|ات|ة|ه)?|نقوش(?:ها|ه)?)[ \t]+(?:ال)?منقوش(?:ة|ه)?(?!\p{L})/gu;
// «جيوب عملية» · «طبقات واضحة» (بنطلون وتنورة 2026-09-15): الصفة تُحذف ويبقى اسم التفصيل، إلا إن كتبها التاجر.
const DETAIL_NOUN = "(?:جيوب|جيب|طبقات|كسرات(?:[ \\t]+عريض(?:ة|ه))?|كشكش|[أا]زرار|تطريز|ترتر|خرز|حزام|رباط|سحاب|تفاصيل|فتح(?:ة|ه)[ \\t]+جانبي(?:ة|ه))";
const EMPTY_QUALIFIER = new RegExp(`((?<!\\p{L})(?:و|ب)?(?:ال)?${DETAIL_NOUN})[ \\t]+(?:ال)?(?:عملي|واضح)(?:ة|ه)?(?!\\p{L})`, "gu");

/** صفات فارغة على التفاصيل وتكرار النقشة — بالنثر والنصوص القصيرة. */
export function dropEmptyQualifiers(text, sourceText = "") {
  const src = normAr(sourceText);
  return String(text || "")
    .replace(PATTERN_TAUTOLOGY, "")
    .replace(EMPTY_QUALIFIER, (m, noun) => (src.includes(normAr(m).trim().replace(/^(?:و|ب)(?=\p{L}{3,})/u, "")) ? m : noun))
    .replace(/[ \t]{2,}/g, " ").replace(/[ \t]+([،.!؟])/gu, "$1");
}
