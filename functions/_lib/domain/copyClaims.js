/** رموز الادعاءات غير المسندة في نص: عائلة رُصدت وليست بأي جذر من بيانات التاجر. */
export function unsourcedClaims(text, sourceText = "") {
  const t = String(text || "");
  if (!t.trim()) return [];
  const src = norm(sourceText).toLowerCase();
  return CLAIM_FAMILIES.filter((f) => f.re.test(t) && !f.roots.some((r) => src.includes(norm(r).toLowerCase()))).map((f) => f.code);
}

// ── خاتمة جدول المقاسات ──────────────────────────────────────────────────────────────────────
const SIZED = /(?:فستان|فساتين|تنور|تنانير|بلوز|بلايز|عباي|قميص|قمصان|بنطال|بنطلون|بناطيل|جاكيت|جاكت|ثوب|ثياب|جلابي|كنز|بدل|جمبسوت|شورت|جينز|بيجام|هودي|سويتر|كارديجان|حذاء|أحذية|احذية|جزم|نعال|صندل|كعب|سنيكرز|ملابس|أزياء|ازياء)/u;
const NOT_SIZED = /(?:شماغ|غتر|طرح|شال|وشاح|حقيب|شنط|كلتش|عطر|عطور|بخور|عود|دهن|ساعة|ساعات|خاتم|عقد|سوار|اسوار|أسوار|حلق|قلاد|مجوهر|نظار)/u;
const MEN = /(?:رجال|للرجال|ثوب|ثياب|شماغ|غتر|بشت[ \t]+رجالي|جلابية[ \t]+رجالي)/u;

/** «sized» (ملابس وأحذية) أو «none» — من اسم المنتج وفئته. */
export function sizeChartKind({ name = "", category = "" } = {}) {
  const t = `${name} ${category}`;
  if (NOT_SIZED.test(String(name || "")) && !SIZED.test(String(name || ""))) return "none";
  return SIZED.test(t) && !NOT_SIZED.test(String(name || "")) ? "sized" : "none";
}

const CHART_SENTENCE = /[^.!؟\n]*(?:جدول[ \t]+المقاسات|اختيار[ \t]+المقاس)[^.!؟\n]*[.!؟]?/gu;

/** خاتمة جدول المقاسات: تُحذف لغير الملابس والأحذية، وتُذكَّر صيغتها لمنتج رجالي. */
export function fixSizeChartClosing(text, { name = "", category = "" } = {}) {
  let t = String(text || "");
  if (sizeChartKind({ name, category }) === "none") {
    return t.replace(CHART_SENTENCE, "").replace(/[ \t]+\n/g, "\n").replace(/\n{3,}/g, "\n\n").trim();
  }
  if (MEN.test(`${name} ${category}`)) {
    t = t.replace(/(?<!\p{L})راجعي(?!\p{L})/gu, "راجع").replace(/(?<!\p{L})تحققي(?!\p{L})/gu, "تحقق").replace(/(?<!\p{L})اختاري(?!\p{L})/gu, "اختر");
  }
  return t;
}
