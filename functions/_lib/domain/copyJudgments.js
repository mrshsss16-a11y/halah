// طبقة أحكام الجودة الواحدة لكل حقول الصفحة (2026-09-13).
//
// حالات صناعية بأنماط نماذجنا أفلتت كلها: «ساحرة»، «تخطف الأنظار»، «راقٍ» بتنوين الكسر، «تجنن»، «لا مثيل لها».
// السبب: القائمة كانت بمكانين (JUDGMENTS بـcopyParse للرصد، ADJ بـcopyPhrases للحذف) فأفلت ما غاب عن أحدهما،
// والحقول القصيرة (العنوان، الوسوم، نص البديل، النقاط) لم تُنظَّف من الأحكام أصلاً — والنقطة المعيبة كانت تُحذف
// كاملة («عباية كحلي بقماش كريب فاخر»). هنا مصدر واحد: كلمات وتعابير، وما ورد ببيانات التاجر يبقى
// («مريح» لبلوزة «قطن مريحة»). بنمطين: جملة (stripJudgments) وكلمة (stripJudgmentWords).

// الإزالة من الجملة بدل حذفها كلها (2026-09-11): «القصّة مستقيمة تعطيها لمسة من الأناقة…» — حذف الجملة أسقط
// معلومة صحيحة. تُزال العبارة وتبقى الجملة، إلا إن بقي منها أقل من أربع كلمات أو بدأت بإشارة.

const T = "[\\u064B-\\u0652]*"; // تشكيل وتنوين: «راقٍ»، «أنيقاً»، «تكلّف»
const normAr = (t) => String(t || "").replace(/[ً-ْـ]/g, "").replace(/[أإآ]/g, "ا").replace(/ة/g, "ه").replace(/ى/g, "ي");
/** كلمة مطبَّعة ⇒ نمط يقبل صور كتابتها (أ/ا، ة/ه، ى/ي) وتشكيلها. */
const loose = (w) => [...w].map((ch) => (ch === " " ? "[ \\t]+" : `${{ "ا": "[اأإآ]", "ه": "[هة]", "ي": "[يى]" }[ch] || ch}${T}`)).join("");

const ADJ_STEMS = ["انيق", "فاخر", "فخم", "مريح", "متين", "مثالي", "جميل", "جمالي", "فريد", "مميز", "عصري", "جذاب", "رائع", "راقي", "راق",
  // حالات 2026-09-13
  "ساحر", "خلاب", "متالق", "لافت", "ملفت", "مبهر", "استثنائي"];
const NOUN_STEMS = ["اناقه", "اناقت", "فخامه", "فخامت", "جمال", "رقي"];
// «راق» بلا تاء: «براقة» لمعة لا حكم.
const alt = (stems) => stems.map((s) => (s === "راق" ? `ر${T}[اأإآ]${T}ق(?![ةه])` : loose(s))).join("|");
const sourced = (stem, src) => new RegExp(`(?<!\\p{L})(?:و|ب|ل)?(?:ال)?${stem}`, "u").test(normAr(src));
const unsourcedStems = (stems, src) => stems.filter((s) => !sourced(s, src));
const INTENS = `(?:[ \\t]+(?:جد${T}ا${T}|للغاي(?:ة|ه)))?`;
function adjFor(src) {
  const stems = unsourcedStems(ADJ_STEMS, src);
  return stems.length ? `(?:${alt(stems)})(?:ة|ه)?${T}(?:ا${T})?${INTENS}` : "(?!)";
}

// تعابير مدح لا تصف القطعة — تُحذف مهما كانت الصفة المجاورة.
const IDIOMS = [
  `(?:ت|ي)(?:خطف|لفت|جذب|سرق)[ \\t]+(?:ال)?(?:[أا]نظار|نظر|انتباه|قلوب)(?:[ \\t]+فعل${T}ا${T})?`,
  // نقاط nexos 2026-09-13: «الطول الماكسي يمنح الإطلالة امتداداً واضحاً» · «الشق الجانبي يضيف تفصيلاً بارزاً للتنورة».
  `(?:ت|ي)منح(?:ك|كِ|ها|ه)?[ \\t]+(?:ال)?[إا]طلال(?:ة|ه)[^.،؟!\\n]*`,
  `(?:ت|ي)ضيف[ \\t]+تفصيل${T}(?:ا${T})?[ \\t]+(?:بارز|واضح|لافت)${T}(?:ا${T})?`,
  `(?:ت|ي)(?:جنن|هبل)`,
  `(?:ت|ي)فتح[ \\t]+(?:ال)?نفس(?:[ \\t]+والله)?`,
  `(?:لا|ما)[ \\t]+(?:مثيل[ \\t]+(?:لها|له)|(?:لها|له)[ \\t]+مثيل)`,
  `لا[ \\t]+غنى[ \\t]+عن(?:ها|ه)(?:[ \\t]+(?:في|ب)[ \\t]*خزانت(?:ك|ها))?`,
  `خيار${T}(?:ا${T})?[ \\t]+موفق${T}(?:ا${T})?(?:[ \\t]+(?:ل|في[ \\t]+)(?:كل|أي|اي)[ \\t]+(?:وقت|مناسب(?:ة|ه)))?`,
  `(?:ت|ي)(?:ليق[ \\t]+ب|عكس[ \\t]+ذوق)[^.،؟!\\n]*`,
  `ذوق(?:ك|كِ)?[ \\t]+(?:ال)?رفيع`,
  `(?:بلا|بدون)[ \\t]+تكل${T}ف`,
  // حتى نهاية المقطع: «يمنحك ثقة واضحة طوال اليوم» — القصّ عند كلمة واحدة نشر «وقماشه المريح واضحة طوال اليوم».
  `(?:ت|ي)منح(?:ك|كِ)?[ \\t]+(?:ال)?(?:ثق(?:ة|ه)|حضور${T}(?:ا${T})?)[^.،؟!\\n]*`,
  `(?:ت|ي)ضيف[ \\t]+(?:ال)?رق(?:ة|ه)`,
  `(?:مع[ \\t]+|ب)?لمس(?:ة|ه)[ \\t]+[أا]نثوي(?:ة|ه)[ \\t]+رقيق(?:ة|ه)`,
  `(?:و)?(?:ت|ي)ناسب[ \\t]+(?:كل|أي|اي)[ \\t]+وقت`,
  `(?:و)?(?:ت|ي)ناسب[ \\t]+(?:مختلف|جميع|كل)[ \\t]+(?:ال)?(?:[أا]ذواق|[أا]عمار)(?:[ \\t]+و(?:ال)?(?:[أا]ذواق|[أا]عمار))?`,
  // «ناعم» و«رقيق» و«أنثوي» قد تكون ملمساً أو قصّة؛ مع «جداً»/«بامتياز» صارت مدحاً. قبل «بامتياز» المنفردة
  // وإلا حُذفت وحدها وبقيت نقطة «إطلالة أنثوية ناعمة».
  `(?:[أا]نثوي|ناعم|رقيق)(?:ة|ه)?(?:[ \\t]+(?:[أا]نثوي|ناعم|رقيق)(?:ة|ه)?)?[ \\t]+(?:جد${T}ا${T}|للغاي(?:ة|ه)|بامتياز)`,
  `بامتياز`,
  `لا[ \\t]+(?:ي|ت)${T}نس(?:ى|ي)`,
  `(?:ب|و)?(?:(?:ذات|ذو|من)[ \\t]+)?(?:عالي(?:ة|ه)?[ \\t]+(?:ال)?جود(?:ة|ه)|(?:ال)?جود(?:ة|ه)[ \\t]+(?:ال)?عالي(?:ة|ه))`,
  // معجم الحشو (معيار ٧.٥، 2026-09-15): «قصّة واسعة تمنح التصميم حضوراً واضحاً»، «يمكن تنسيقه مع حذاء بسيط لإطلالة خفيفة».
  `(?:(?:ت|ي)منح(?:ه|ها)?[ \\t]+(?:ال)?\\p{L}+[ \\t]+)?حضور${T}(?:ا${T})?[ \\t]+واضح${T}(?:ا${T})?`,
  `(?:ب)?تنسيق[ \\t]+بارز`,
  // «بارز» حكماً على التصميم أو التفاصيل وحدهما؛ «خط بارز» أو «نقش بارز» وصف ملمس يبقى.
  `(?<=(?:تصميم|تفاصيل|تفصيل|تفاصيله|تفاصيلها)[ \\t]+)(?:ال)?بارز(?:ة|ه)?${T}(?:ا${T})?`,
  `(?:ت|ي)ضيف[ \\t]+لمس(?:ة|ه)[^.،؟!\\n]*`,
  `(?:ل|ب)?[إا]طلال(?:ة|ه)[ \\t]+(?:مميز|متكامل|خفيف)(?:ة|ه)?`,
  `(?:ل|ب)?تنسيق[ \\t]+متكامل`,
  `(?:و)?(?:(?:يمكن(?:ك)?|تقدرين|تقدر)[ \\t]+تنسيق(?:ه|ها)|(?:ت|ي)${T}ن${T}س${T}ق${T})[ \\t]+مع[ \\t]+(?:(?:ال)?[إا]كسسوارات(?:[ \\t]+(?:ال)?بسيط(?:ة|ه)?)?|(?:ال)?(?:حذاء|[أا]حذية)[ \\t]+(?:ال)?بسيط(?:ة|ه)?)(?!\\p{L})`
].map((s) => new RegExp(`(?<!\\p{L})${s}(?!\\p{L})`, "u"));

const idiomSourced = (m, src) => normAr(src).includes(normAr(m).trim());
const wordRe = (src, flags = "u") => {
  const stems = unsourcedStems([...ADJ_STEMS, ...NOUN_STEMS], src);
  return stems.length ? new RegExp(`(?<!\\p{L})(?:و|ب|ل)?(?:ال)?(?:${alt(stems)})(?:ة|ه|ا|ها)?${T}(?:ا${T})?${INTENS}(?!\\p{L})`, flags) : null;
};

/** أول حكم جودة أو تعبير مدح في النص لم يرد ببيانات التاجر، مع موضعه — وإلا null. */
function firstJudgment(text, sourceText = "") {
  const t = String(text || "");
  const hits = IDIOMS.map((re) => t.match(re)).filter((m) => m && !idiomSourced(m[0], sourceText)).map((m) => ({ text: m[0], index: m.index, idiom: true }));
  const w = wordRe(sourceText)?.exec(t);
  if (w) hits.push({ text: w[0], index: w.index, idiom: false });
  return hits.sort((a, b) => a.index - b.index)[0] || null;
}
/** تعبير مدح كامل غير مسند («يلفت النظر»، «يمنح الإطلالة…») — النقطة المبنية عليه لا يبقى منها وصف. */
export function hasPraiseIdiom(text, sourceText = "") {
  const t = String(text || "");
  return IDIOMS.some((re) => { const m = t.match(re); return m && !idiomSourced(m[0], sourceText); });
}
export function unsourcedJudgment(text, sourceText = "") {
  return firstJudgment(text, sourceText)?.text.trim() || null;
}

/** يحذف مقاطع الجملة (بين الفواصل) التي يطابقها `bad` ويحفظ نهايتها: «عطر ورد عود، حجم 100 مل، الحقي بطلبك.» */
export function dropClauses(sentence, bad) {
  const s = String(sentence || "").trim();
  const end = (s.match(/[.!؟]+$/u) || [""])[0];
  const parts = s.slice(0, s.length - end.length).split(/[ \t]*،[ \t]*/u);
  const kept = parts.filter((c) => c.trim() && !bad(c));
  if (kept.length === parts.length) return s;
  if (!kept.length) return "";
  if (kept[0] !== parts[0]) kept[0] = kept[0].replace(/^و(?=[تيبل]\p{L}{2,})/u, "");
  return `${kept.join("، ")}${kept[kept.length - 1] === parts[parts.length - 1] ? end : "."}`;
}

// مقطع مدح خالص يُحذف كاملاً (2026-09-13): يبدأ بموضوع المدح أو فعل الإضفاء والحكم يليه مباشرة («إطلالتها
// متألقة»، «تصميمه استثنائي»، «يمنحك إطلالة أنيقة»)، أو يبدأ بالتعبير نفسه («يلفت الأنظار بأناقته»، «قطعة لا غنى
// عنها»). حذف الكلمة وحدها ترك «إطلالتها في مكان العمل بفضل قصّتها». «تصميمها السادة والفاخر يجعلها…» يبقى:
// الحكم معطوف على وصف حقيقي.
const PRAISE_HEAD = /^(?:و|ف)?(?:(?:[إا]طلالت|تصميم|شكل|راحت|رائحت|ريحت|ملمس|حضور|جمال|[أا]ناقت|فخامت|رقي)(?:ها|ه)|[إا]طلال(?:ة|ه)|(?:ت|ي)(?:منح|عطي|ضفي|ضيف)(?:ك|ها|ه)?)$/u;
function praiseClause(clause, sourceText, head) {
  const words = clause.trim().split(/\s+/);
  if (head && normAr(words[0]).replace(/^و/, "") === head) return false;
  const hit = firstJudgment(clause, sourceText);
  if (!hit) return false;
  const at = clause.slice(0, hit.index).trim().split(/\s+/).filter(Boolean).length;
  if (at === 0 || (hit.idiom && at === 1)) return true;
  return PRAISE_HEAD.test(words[0].replace(/[^\p{L}]/gu, "")) && (at === 1 || (at === 2 && !/^و/.test(hit.text.trim())));
}

function patternsFor(ADJ) {
  const OWN = "(?:جمال|[أا]ناقت|[أا]ناقة|فخامت|فخامة)(?:ه|ها)?";
  const NOUN = "(?:ال)?(?:[أا]ناقة|فخامة|رقي|راحة)";
  return [
    // مقطع «مما يجعلها مثالية للارتداء…» يُحذف كله، فحذف الصفة وحدها ترك «مما يجعلها للارتداء» (2026-09-12 00:21).
    new RegExp(`\\s*،?\\s*مما\\s+(?:ي|ت)(?:جعل|ضيف|منح|عطي|ضفي)(?:ها|ه)?\\s+[^.،؟!\\n]*?${ADJ}(?![\\p{L}])[^.،؟!\\n]*`, "gu"),
    // «تعطيها لمسة من الأناقة» · «يمنحها طابعاً من الفخامة»
    new RegExp(`\\s*،?\\s*(?:و)?(?:ت|ي)?(?:عطي|منح|ضفي|ضيف)(?:ها|ه|ك)?\\s+(?:لمسة|طابع(?:اً|ا)?|إطلالة|اطلالة)\\s+(?:من\\s+)?${NOUN}(?:\\s+(?:على|في)\\s+(?:أي|اي|كل)\\s+\\p{L}+)?`, "gu"),
    // «تعطي مظهراً أنيقاً» — وبقاياها «تعطي مظهراً.»
    new RegExp(`\\s*،?\\s*(?:و)?(?:ت|ي)(?:عطي|منح|ضفي|ضيف|وفر)(?:ها|ه|ك)?\\s+(?:مظهر(?:اً|ًا|ا)?|إطلالة|اطلالة|لمسة|طابع(?:اً|ًا|ا)?)(?:\\s+${ADJ}){0,2}(?=\\s*[.،؟!]|$)`, "gu"),
    // «يعطيها مظهرًا فخمًا يناسب المناسبات» ⇒ «يناسب المناسبات» (2026-09-12 19:48)؛ «تمنحك إطلالة رجولية راقية» (2026-09-13)
    new RegExp(`\\s*(?:و)?(?:ت|ي)(?:عطي|منح|ضفي|ضيف)(?:ها|ه|ك)?\\s+(?:مظهر(?:اً|ًا|ا)?|إطلالة|اطلالة|لمسة|طابع(?:اً|ًا|ا)?|راحة)(?:\\s+(?!و)(?!${ADJ})\\p{L}+)?(?:\\s+(?:و)?${ADJ}){1,2}(?:\\s+(?:في\\s+نفس\\s+الوقت|بنفس\\s+الوقت|في\\s+الوقت\\s+نفسه|(?:في|ل)\\s*(?:كل|أي)\\s+(?:مناسبة|وقت)))?(?![\\p{L}])`, "gu"),
    // «تبرز جمال إطلالتك» — الفعل والحكم ومفعوله معاً (تنورة 2026-09-12 21:19)
    new RegExp(`\\s*،?\\s*(?:و)?(?:ت|ي)(?:زيد|ضيف|برز|عزز)\\s+(?:من\\s+|إلى\\s+|الى\\s+)?${OWN}\\s+(?:[إا]طلالت(?:ك|ها|ه)|مظهر(?:ك|ها|ه))(?![\\p{L}])`, "gu"),
    // «للطلعات اللي تحتاج أناقة» ⇒ «للطلعات»
    new RegExp(`\\s*(?:اللي|الي|التي|الذي)\\s+(?:ت|ي)حتاج\\s+(?:إلى\\s+|الى\\s+|لـ?\\s*)?${NOUN}(?![\\p{L}])`, "gu"),
    // «تزيد من جماله وأناقته» · «تضيف إلى أناقتها»
    new RegExp(`\\s*،?\\s*(?:و)?(?:ت|ي)(?:زيد|ضيف|برز|عزز)\\s+(?:من\\s+|إلى\\s+|الى\\s+)?${OWN}(?:\\s+و${OWN})?`, "g"),
    // «لإضافة لمسة أنيقة» · «لإضفاء لمسة من الأناقة» (2026-09-11 23:08)
    new RegExp(`\\s*،?\\s*(?:ل|و)?(?:إضافة|اضافة|إضفاء|اضفاء|منح|إعطاء|اعطاء)\\s+(?:لمسة|طابع)(?:\\s+(?:من\\s+)?(?:${NOUN}|${ADJ}))?(?![\\p{L}])`, "gu"),
    // «بلمسة من الأناقة» · «مع طابع من الفخامة»
    new RegExp(`\\s*،?\\s*(?:ب|مع\\s+)(?:لمسة|طابع|إطلالة|اطلالة)\\s+(?:من\\s+)?${NOUN}`, "g"),
    // «بتصميم أنيق» · «وتصميم أنيق» (تنورة 2026-09-12 18:40) · «وتفصيل أنيق» (2026-09-13)
    new RegExp(`\\s*(?<!\\p{L})(?:و|ب|وب)(?:تصميم|طابع|لمسة|إطلالة|اطلالة|شكل|مظهر|تفصيل|تفاصيل)\\s+${ADJ}(?![\\p{L}])`, "gu"),
    // صفة منفردة: «أنيقة»، «والفاخر»، «راقٍ»
    new RegExp(`\\s*(?<!\\p{L})(?:و)?(?:ال)?${ADJ}(?![\\p{L}])`, "gu")
  ];
}
const NOUN_WORD = (src) => {
  const stems = unsourcedStems(NOUN_STEMS, src);
  return stems.length ? new RegExp(`[ \\t]*(?<!\\p{L})(?:و|ب|ل)?(?:ال)?(?:${alt(stems)})(?:ه|ها)?${T}(?!\\p{L})`, "gu") : /(?!)/g;
};
function dropIdioms(text, sourceText) {
  return IDIOMS.reduce((t, re) => t.replace(new RegExp(`[ \\t]*${re.source}`, "gu"), (m) => (idiomSourced(m, sourceText) ? m : "")), String(text || ""));
}

/** جملة واحدة: تُزال عبارات الحكم، أو مقاطع المدح الخالص، وتبقى الجملة إن بقي منها ما يُقرأ. */
export function stripJudgments(sentence, { sourceText = "", name = "" } = {}) {
  const ADJ = adjFor(sourceText);
  const head = normAr(String(name || "").trim().split(/\s+/)[0] || "");
  let s = dropClauses(String(sentence || ""), (c) => praiseClause(c, sourceText, head));
  // مقطع سليم بقي بعد حذف مقطع حشو («يناسب الإطلالات النهارية، ويمكن تنسيقه مع حذاء بسيط…» والتاجر ذكر النهارية،
  // 2026-09-15): جملة تامة من ثلاث كلمات تبقى، فحدّ الأربع كلمات للبقايا المبتورة داخل المقطع.
  const wholeClause = s !== String(sentence || "").trim() ? s : "";
  // «هذه البلوزة مثالية للمناسبات…» ⇒ «تناسب المناسبات…» (2026-09-12 00:31).
  s = s.replace(new RegExp(`^\\s*(?:(?:هذه|هذا|هذي)\\s+)?ال\\p{L}+\\s+${ADJ}\\s+لل`, "u"), "تناسب ال");
  // «إطلالة أنيقة وعملية» ⇒ «إطلالة عملية» (2026-09-12 00:06).
  s = s.replace(new RegExp(`(?<=(?:إطلالة|اطلالة|مظهر|قطعة)(?:اً|ًا|ا)?)\\s+(?:ال)?${ADJ}\\s+و(?=\\p{L})`, "gu"), " ");
  s = dropIdioms(s, sourceText);
  for (const re of patternsFor(ADJ)) s = s.replace(re, "");
  // بقايا: «لإطلالة.» و«، هذه البلوزة.» (2026-09-12 00:17)؛ (?<!\p{L}) كي لا يُقص «الإطلالة» (02:22).
  // «بمحاذاة الياقة للتصميم.» بعد حذف «تضيف تفصيلاً واضحاً» (جولة الجاهزية 2026-09-13).
  s = s.replace(/\s*(?<!\p{L})(?:ل|ب)(?:إطلالة|اطلالة|مظهر(?:اً|ًا|ا)?|لمسة|لتصميم|التصميم)(?=\s*[.،؟!]|\s*$)/gu, "")
    .replace(/\s*،?\s*(?:هذه|هذا|هذي)\s+\p{L}+(?=\s*[.؟!]|\s*$)/gu, "");
  s = s.replace(/\s*،\s*(?=[.،؟!]|$)/g, "").replace(/\s{2,}/g, " ").replace(/^\s*[،,]\s*/, "").trim();
  const words = s.split(/\s+/).filter(Boolean).length;
  if ((words < 4 && !(words === 3 && s === wholeClause)) || /^(هذه|هذا|هذي)(?=\s)/.test(s)) return "";
  return s;
}

/** نص قصير (عنوان، نقطة، وسم، مواصفة): تُحذف كلمة الحكم وتعبيره بلا حدّ أدنى — «فستان سهرة كلوش ساحر» ⇒ «فستان سهرة كلوش». */
export function stripJudgmentWords(text, sourceText = "") {
  let t = String(text || "");
  if (!firstJudgment(t, sourceText)) return t;
  t = dropIdioms(t, sourceText);
  for (const re of patternsFor(adjFor(sourceText))) t = t.replace(re, "");
  return t.replace(NOUN_WORD(sourceText), "")
    .replace(/[ \t]+(?<!\p{L})و(?=[ \t]*(?:$|[،.؟!|]))/gu, "")
    .replace(/[ \t]{2,}/g, " ").replace(/[ \t]+([،.؟!])/gu, "$1").replace(/^[ \t،]+|[ \t،]+$/gu, "");
}
