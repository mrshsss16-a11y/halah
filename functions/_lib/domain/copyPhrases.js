// إزالة عبارة حكم الجودة من جملة بدل حذف الجملة كلها (2026-09-11).
//
// مخرج حقيقي على متجر المراجعة: كاتب الوصف المركّز كتب جملة افتتاحية فيها حكم جودة، فحذف
// التنظيف الجملة كاملة وبدأ الوصف المنشور بـ«القصّة مستقيمة تعطيها لمسة من الأناقة…» — بلا
// اسم المنتج. الحذف الكامل صحيح للسعر والادعاءات، لكنه يُسقط معلومة صحيحة حين يكون العيب
// صفة واحدة. هنا تُزال العبارة وتبقى الجملة، إلا إن بقي منها أقل من أربع كلمات أو بدأت
// بإشارة («هذه البلوزة للمناسبات») فتُحذف كما كانت.
//
// مستقل عن copyParse.js لأن ذلك الملف عند سقف ٤٠٠ سطر (scripts/audit-file-size.mjs).

// التنوين يُكتب بعد الألف أو قبلها («أنيقًا»/«أنيقاً»)، ومع التاء («أنيقةً»).
const ADJ = "(?:[أا]نيق|فاخر|مريح|متين|مثالي|جميل|جمالي|فريد|مميز|عصري|جذاب|رائع|راق(?:ي)?)(?:ة|ه)?(?:اً|ًا|ا|ً)?";
const OWN = "(?:جمال|[أا]ناقت|[أا]ناقة|فخامت|فخامة)(?:ه|ها)?";
const NOUN = "(?:ال)?(?:[أا]ناقة|فخامة|رقي|راحة)";
const PATTERNS = [
  // مقطع «مما يجعلها مثالية للارتداء…» · «مما يضيف تفاصيل رائعة ومميزة» — يُحذف المقطع كله لا صفته
  // وحدها، فحذف الصفة وحدها ترك «مما يجعلها للارتداء» (2026-09-12 00:21).
  new RegExp(`\\s*،?\\s*مما\\s+(?:ي|ت)(?:جعل|ضيف|منح|عطي|ضفي)(?:ها|ه)?\\s+[^.،؟!\\n]*?${ADJ}(?![\\p{L}])[^.،؟!\\n]*`, "gu"),
  // «تناسب مختلف الأذواق» — ادعاء عام لا يصف القطعة
  new RegExp(`\\s*،?\\s*(?:و)?(?:ت|ي)ناسب\\s+(?:مختلف|جميع|كل)\\s+(?:الأذواق|الاذواق|الأعمار|الاعمار)`, "gu"),
  // «تعطيها لمسة من الأناقة» · «يمنحها طابعاً من الفخامة»
  new RegExp(`\\s*،?\\s*(?:و)?(?:ت|ي)?(?:عطي|منح|ضفي|ضيف)(?:ها|ه|ك)?\\s+(?:لمسة|طابع(?:اً|ا)?|إطلالة|اطلالة)\\s+(?:من\\s+)?${NOUN}`, "g"),
  // «تعطي مظهراً أنيقاً» · «تمنحها إطلالة فاخرة» — وبقاياها «تعطي مظهراً.»
  new RegExp(`\\s*،?\\s*(?:و)?(?:ت|ي)(?:عطي|منح|ضفي|ضيف|وفر)(?:ها|ه|ك)?\\s+(?:مظهر(?:اً|ًا|ا)?|إطلالة|اطلالة|لمسة|طابع(?:اً|ًا|ا)?)(?:\\s+${ADJ}){0,2}(?=\\s*[.،؟!]|$)`, "gu"),
  // «تزيد من جماله وأناقته» · «تضيف إلى أناقتها»
  new RegExp(`\\s*،?\\s*(?:و)?(?:ت|ي)(?:زيد|ضيف|برز|عزز)\\s+(?:من\\s+|إلى\\s+|الى\\s+)?${OWN}(?:\\s+و${OWN})?`, "g"),
  // «لإضافة لمسة أنيقة» · «لإضفاء لمسة من الأناقة» — وبقاياها «لإضافة لمسة» (مخرج حقيقي 2026-09-11 23:08)
  new RegExp(`\\s*،?\\s*(?:ل|و)?(?:إضافة|اضافة|إضفاء|اضفاء|منح|إعطاء|اعطاء)\\s+(?:لمسة|طابع)(?:\\s+(?:من\\s+)?(?:${NOUN}|${ADJ}))?(?![\\p{L}])`, "gu"),
  // «بلمسة من الأناقة» · «مع طابع من الفخامة»
  new RegExp(`\\s*،?\\s*(?:ب|مع\\s+)(?:لمسة|طابع|إطلالة|اطلالة)\\s+(?:من\\s+)?${NOUN}`, "g"),
  // «بتصميم أنيق» · «بإطلالة فاخرة» · «وتصميم أنيق» (بقي «وتصميم،» معلّقاً بتنورة 2026-09-12 18:40)
  new RegExp(`\\s*(?:و|ب|وب)(?:تصميم|طابع|لمسة|إطلالة|اطلالة|شكل|مظهر)\\s+${ADJ}(?![\\p{L}])`, "gu"),
  // صفة منفردة: «أنيقة»، «والفاخر»
  new RegExp(`\\s*(?:و)?(?:ال)?${ADJ}(?![\\p{L}])`, "gu")
];

export function stripJudgments(sentence) {
  let s = String(sentence || "");
  // «هذه البلوزة مثالية للمناسبات…» ⇒ «تناسب المناسبات…» — الجملة الإشارية كانت تُحذف كاملة
  // ومعها اقتراح التنسيق (2026-09-12 00:31).
  s = s.replace(new RegExp(`^\\s*(?:(?:هذه|هذا|هذي)\\s+)?ال\\p{L}+\\s+${ADJ}\\s+لل`, "u"), "تناسب ال");
  // «إطلالة أنيقة وعملية» ⇒ «إطلالة عملية» لا «إطلالة وعملية» (مخرج حقيقي 2026-09-12 00:06).
  s = s.replace(new RegExp(`(?<=(?:إطلالة|اطلالة|مظهر|قطعة)(?:اً|ًا|ا)?)\\s+(?:ال)?${ADJ}\\s+و(?=\\p{L})`, "gu"), " ");
  for (const re of PATTERNS) s = s.replace(re, "");
  // بقايا بعد حذف الصفة: «لإطلالة.» و«، هذه البلوزة.» (مخرج حقيقي 2026-09-12 00:17).
  // (?<!\p{L}): بلاه طابق «لإطلالة» داخل «الإطلالة» فبقي «على ا.» (2026-09-12 02:22).
  s = s.replace(/\s*(?<!\p{L})(?:ل|ب)(?:إطلالة|اطلالة|مظهر(?:اً|ًا|ا)?|لمسة)(?=\s*[.،؟!]|\s*$)/gu, "")
    .replace(/\s*،?\s*(?:هذه|هذا|هذي)\s+\p{L}+(?=\s*[.؟!]|\s*$)/gu, "");
  s = s.replace(/\s*،\s*(?=[.،؟!]|$)/g, "").replace(/\s{2,}/g, " ").replace(/^\s*[،,]\s*/, "").trim();
  const words = s.split(/\s+/).filter(Boolean).length;
  if (words < 4 || /^(هذه|هذا|هذي)(?=\s)/.test(s)) return "";
  return s;
}

// الوصف يُنشر فقرات (composeDescriptionHtml: كل سطر فارغ = <p>). التنظيف كان يقسم إلى جمل
// ويعيد وصلها بمسافة، فكل وصف نُظّف نُشر كتلة واحدة بلا فقرات (كُشف باختبار PL-15).
export function splitSentencesKeep(text) {
  return String(text || "").trim().split(/\n\s*\n/).flatMap((para, p) => para.split(/(?<=[.!؟\n])\s+/).map((s) => ({ s: s.trim(), p })));
}
export function joinSentences(items) {
  const paras = new Map();
  for (const { s, p } of items) if (s) paras.set(p, [...(paras.get(p) || []), s]);
  return [...paras.values()].map((a) => a.join(" ")).join("\n\n").trim();
}

// عناوين ملاحظات الرؤية تتسرّب للوصف المنشور: «الطول والقصّة ميدي…»، «بياقة حمالات».
export function fixNoteLabels(text) {
  return String(text || "")
    .replace(/(?<!\p{L})(?:ال)?طول\s+والقص[ّ]?ة\s*:?\s*/gu, "بطول ")
    .replace(/(?<!\p{L})(?:ال)?كتفان\s+والحمالات\s*:?\s*/gu, "")
    .replace(/(?<!\p{L})(ب)?ياقة\s+(?=حمالات)/gu, "$1")
    .replace(/(?<!\p{L})(?:ال)?طابع\s+العام\s*:\s*/gu, "")
    // «لإبراز الطابع العام الهادئ» — العنوان بلا نقطتين (بنطلون 2026-09-12 02:22).
    .replace(/[ \t]*(?:لإبراز|لابراز|لتعزيز|مع|يناسب|تناسب)[ \t]+(?:ال)?طابع[ \t]+العام(?:[ \t]+(?!و)\p{L}+)?/gu, "")
    .replace(/(?<!\p{L})(?:ال)?طابع[ \t]+العام(?!\p{L})/gu, "الطابع");
}

// «بطول ميدي» لبلوزة لم تذكر ملاحظات صورتها طولاً (2026-09-12 00:17): مثال بتعليمات الكاتب زرعه.
export function dropUnseenLength(text, notes) {
  if (!notes) return String(text || "");
  return String(text || "")
    .replace(/(?:[ \t]*،)?[ \t]*(?:و)?(?:ب)?(?:ال)?طول[ \t]+(ميدي|ماكسي|ميني)(?!\p{L})/gu, (m, w) => (notes.includes(w) ? m : ""))
    .replace(/(^|[.!؟][ \t]+|\n)[ \t]*و(?=قص|ب|مع)/gu, "$1");
}

// تنورة 2026-09-12 18:29: الملاحظات بلا قصّة ولا خصر، والكاتب نشر «بخصر مرتفع، تتميز بقصّتها المستقيمة»
// لتنورة واسعة. صفة قصّة أو خصر أو كسرات لم ترد بالملاحظات ولا ببيانات التاجر تُحذف (حين توجد صورة).
const normCut = (t) => String(t || "").replace(/[ً-ْـ]/g, "").replace(/[أإآ]/g, "ا").replace(/ة/g, "ه").replace(/ى/g, "ي");
const FIT_FAMILIES = [["مستقيم"], ["ضيق"], ["واسع", "فضفاض", "منفوش", "منسدل", "كلوش"], ["مرتفع", "عالي"], ["منخفض"], ["مطاطي"]];
const FIT_RE = /(?<!\p{L})(?:ب|و|ل)?(?:ال)?(?:قص[ّ]?(?:ة|ه|تها|ته)|خصر(?:ها|ه)?)[ \t]+(?:ال)?(مستقيم|ضيق|واسع|فضفاض|منفوش|منسدل|كلوش|مرتفع|عالي|منخفض|مطاطي)\p{L}*/gu;
const PLEAT_RE = /(?<!\p{L})(?:ب|و)?(?:ال)?(?:كسرات|بليسيه|طي[ّ]?ات)(?:[ \t]+(?:ال)?(?:عريض|رفيع|بارز|ناعم|متباعد|كثيف|منتظم)\p{L}*)*/gu;
const seenStem = (src, stem) => new RegExp(`(?<!\\p{L})(?:[وبل])?(?:ال)?${normCut(stem)}`, "u").test(src);
/** عبارات القصّة والخصر والكسرات بالنص التي لا تسندها الملاحظات ولا بيانات التاجر. بلا ملاحظات = لا حكم. */
export function unseenCutPhrases(text, notes, sourceText = "") {
  if (!String(notes || "").trim()) return [];
  const src = normCut(`${notes} ${sourceText}`);
  const out = [];
  for (const m of String(text || "").matchAll(FIT_RE)) {
    const family = FIT_FAMILIES.find((f) => f.includes(m[1])) || [m[1]];
    if (!family.some((stem) => seenStem(src, stem))) out.push(m[0]);
  }
  if (!["كسرات", "بليسيه", "طيات"].some((stem) => seenStem(src, stem))) for (const m of String(text || "").matchAll(PLEAT_RE)) out.push(m[0]);
  return out;
}
/** يحذف العبارة إن بدأ المقطع باسم المنتج («تنورة سوداء بخصر مرتفع»)، وإلا المقطع كاملاً («تتميز بقصّتها المستقيمة…»). */
export function dropUnseenCut(text, { notes = "", sourceText = "", name = "" } = {}) {
  const t = String(text || "");
  if (!unseenCutPhrases(t, notes, sourceText).length) return t;
  const head = normCut(String(name || "").trim().split(/\s+/)[0] || "");
  return t.split(/([.!؟،\n])/u).map((clause, i) => {
    if (i % 2) return clause;
    const bad = unseenCutPhrases(clause, notes, sourceText);
    if (!bad.length) return clause;
    if (head && normCut(clause.trim().split(/\s+/)[0] || "").replace(/^و/, "") === head) return bad.reduce((c, b) => c.replace(b, ""), clause);
    return "";
  }).join("")
    .replace(/،(?:[ \t]*،)+/gu, "،")
    .replace(/[ \t]*،[ \t]*(?=[.!؟\n]|$)/gu, "")
    .replace(/([.!؟\n])[ \t]*،[ \t]*/gu, "$1 ")
    .replace(/([.!؟])(?:[ \t]*[.!؟])+/gu, "$1")
    .replace(/^[ \t]*[.،][ \t]*/u, "")
    .replace(/[ \t]{2,}/g, " ").replace(/[ \t]+([.!؟،])/gu, "$1").replace(/\n[ \t]+/g, "\n").replace(/\n[.!؟][ \t]*/gu, "\n")
    .trim();
}

// حروف صينية/يابانية/كورية وسط النص: «مع بلوزة خفيفة وقب鞋 رياضية» (2026-09-12 00:40). يُحذف
// المعطوف الذي فيه الحرف حتى نهاية المقطع، لا الكلمة وحدها («مع بلوزة خفيفة رياضية» خطأ آخر).
const FOREIGN_SCRIPT = "[\\u3040-\\u30ff\\u3400-\\u9fff\\uf900-\\ufaff\\uac00-\\ud7af]";
export function dropForeignScript(text) {
  return String(text || "")
    .replace(new RegExp(`[ \\t]*،?[ \\t]*(?:و|أو)?[^\\s.،؟!]*${FOREIGN_SCRIPT}[^.،؟!\\n]*`, "gu"), "")
    .replace(new RegExp(FOREIGN_SCRIPT, "gu"), "");
}

// قطعة سفلية لا أكمام لها ولا ياقة: «تنورة ميدي… وبدون أكمام».
const BOTTOM_ITEM = /^(?:ال)?(?:تنور|تنانير|بنطال|بنطلون|بناطيل|شورت|جينز)/u;
export const isBottomItem = (name) => BOTTOM_ITEM.test(String(name || "").trim());
export function dropSleevesForBottoms(text, name) {
  if (!isBottomItem(name)) return String(text || "");
  return String(text || "").replace(/[ \t]*(?:،[ \t]*)?(?:و)?(?:بدون|بلا|بلا\s+ولا)[ \t]+(?:ال)?[أا]كمام(?!\p{L})/gu, "");
}

// ملابس نسائية بلا جملة جدول المقاسات (تنورة 2026-09-12 01:38): جملة ثابتة لا تدّعي شيئاً عن المنتج.
const WOMEN_APPAREL = /^(?:ال)?(?:فستان|فساتين|تنور|تنانير|بلوز|بلايز|عباي|جمبسوت|كارديجان)/u;
export function withSizeChartLine(text, name) {
  const t = String(text || "").trim();
  if (!t || !WOMEN_APPAREL.test(String(name || "").trim()) || /جدول المقاسات/.test(t)) return t;
  return `${t}\n\nراجعي جدول المقاسات قبل الطلب لاختيار المقاس المناسب.`;
}

// كلمات لاتينية داخل الوصف العربي: «في أسفل كل couche» (2026-09-12)، و«تنورة midi» بتفكير نموذج.
// مصطلحات الأزياء الشائعة تُعرَّب؛ غيرها بحروف صغيرة (٣+) يُحذف ما لم يكتبه التاجر (علامة تجارية مثلاً).
// الأحرف الكبيرة (XL، A) لا تُمس: مقاسات وقصّات.
const LATIN_FASHION = { couche: "طبقة", couches: "طبقات", layer: "طبقة", layers: "طبقات", tiered: "بطبقات", tier: "طبقة", tiers: "طبقات", midi: "ميدي", maxi: "ماكسي", mini: "ميني", ruffle: "كشكش", ruffles: "كشاكش", ruffled: "بكشكش", pleated: "بكسرات", pleats: "كسرات" };
export function fixLatinWords(text, sourceText = "") {
  const src = String(sourceText || "").toLowerCase();
  return String(text || "")
    .replace(/(?<![A-Za-z])[a-z][a-z-]{2,}(?![A-Za-z])/g, (w) => LATIN_FASHION[w] || (src.includes(w) ? w : ""))
    .replace(/[ \t]{2,}/g, " ")
    .replace(/[ \t]+([.،؟!])/g, "$1");
}

// ماكسي/ميدي/ميني أطوال فساتين وتنانير: «بنطلون… بتصميم ماكسي» (2026-09-12 02:22).
const TROUSERS = /^(?:ال)?(?:بنطال|بنطلون|بناطيل|جينز)/u;
export function fixTrouserLength(text, name) {
  if (!TROUSERS.test(String(name || "").trim())) return String(text || "");
  return String(text || "")
    .replace(/(?<!\p{L})(?:ب)?(?:تصميم|قصّة|قصة)[ \t]+ماكسي(?!\p{L})/gu, "بطول كامل")
    .replace(/(?<!\p{L})ماكسي(?!\p{L})/gu, "بطول كامل");
}

// دعوة بيع لا تصف القطعة: «تسوقي الآن للحصول على…» (فستان 2026-09-12 02:27). الجملة تُحذف كاملة.
export const SALES_CTA = /(?<!\p{L})(?:تسوقي|تسوّقي|اطلبي|اطلبيها|احصلي|سارعي|اقتنيها|لا تفوتي)(?!\p{L})/u;
export function dropSalesCta(text) {
  return joinSentences(splitSentencesKeep(text).filter(({ s }) => !SALES_CTA.test(s)));
}
// «هذا القطع/القطعة» (بنطلون 2026-09-12 02:28)، و«إطلالة عملية في آنٍ واحد» بعد حذف «أنيقة و».
export function fixCommonGrammar(text) {
  return String(text || "")
    .replace(/(?<!\p{L})هذا[ \t]+(?:القطعة|القطع)(?!\p{L})/gu, "هذه القطعة")
    // «بطبعة بايستيل» من ملاحظات Groq (جاكيت 2026-09-12 02:35): اسم الطبعة «بيزلي».
    .replace(/(?<!\p{L})بايستيل(?!\p{L})/gu, "بيزلي")
    .replace(/(?<!\p{L})((?:ل|ب)?(?:إطلالة|اطلالة))[ \t]+(\p{L}+)[ \t]+في[ \t]+آن[ٍ]?[ \t]+واحد(?!\p{L})/gu, "$1 $2");
}

// مطابقة لون مؤنث بعد اسم قطعة نكرة مؤنثة: «تنورة فضي» ⇒ «تنورة فضية» (2026-09-12 02:34).
// «بلون فضي» صحيحة (اللون مذكر) فلا تُمس، ولا المعرّف («التنورة») تجنباً لـ«التنورة فضية».
const FEMININE_ITEM = "(?:تنورة|بلوزة|عباية|سترة|كنزة|بدلة)";
const COLOR_FEMININE = { "أسود": "سوداء", "اسود": "سوداء", "أبيض": "بيضاء", "ابيض": "بيضاء", "أحمر": "حمراء", "احمر": "حمراء", "أخضر": "خضراء", "اخضر": "خضراء", "أزرق": "زرقاء", "ازرق": "زرقاء", "أصفر": "صفراء", "اصفر": "صفراء", "فضي": "فضية", "ذهبي": "ذهبية", "وردي": "وردية", "زيتوني": "زيتونية", "كحلي": "كحلية", "رمادي": "رمادية", "بنفسجي": "بنفسجية", "برتقالي": "برتقالية", "عنابي": "عنابية", "خمري": "خمرية", "نيلي": "نيلية", "سماوي": "سماوية" };
const AGREEMENT = new RegExp(`(?<!\\p{L})((?:و|ب|ل)?${FEMININE_ITEM})[ \\t]+(${Object.keys(COLOR_FEMININE).join("|")})(?!\\p{L})`, "gu");
export function findColorAgreement(text) {
  return [...String(text || "").matchAll(AGREEMENT)].map((m) => ({ wrong: `${m[1]} ${m[2]}`, right: `${m[1]} ${COLOR_FEMININE[m[2]]}` }));
}
export function fixColorAgreement(text) {
  return String(text || "").replace(AGREEMENT, (_m, item, color) => `${item} ${COLOR_FEMININE[color]}`);
}
