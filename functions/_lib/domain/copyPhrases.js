// كلمات لاتينية داخل الوصف العربي: «في أسفل كل couche» (2026-09-12)، و«تنورة midi» بتفكير نموذج.
// مصطلحات الأزياء الشائعة تُعرَّب؛ غيرها بحروف صغيرة (٣+) يُحذف ما لم يكتبه التاجر (علامة تجارية مثلاً).
// الأحرف الكبيرة (XL، A) لا تُمس: مقاسات وقصّات.
const LATIN_FASHION = { couche: "طبقة", couches: "طبقات", layer: "طبقة", layers: "طبقات", tiered: "بطبقات", tier: "طبقة", tiers: "طبقات", midi: "ميدي", maxi: "ماكسي", mini: "ميني", ruffle: "كشكش", ruffles: "كشاكش", ruffled: "بكشكش", pleated: "بكسرات", pleats: "كسرات" };
export function fixLatinWords(text, sourceText = "") {
  const src = String(sourceText || "").toLowerCase();
  return String(text || "")
    .replace(/(?<![A-Za-z])[a-z][a-z-]{2,}(?![A-Za-z])/g, (w) => LATIN_FASHION[w] || (src.includes(w) ? w : ""))
    .replace(/[ \t]{2,}/g, " ")
    .replace(/[ \t]+([.،؟!])/g, "$1");
}

// ماكسي/ميدي/ميني أطوال فساتين وتنانير: «بنطلون… بتصميم ماكسي» (2026-09-12 02:22).
const TROUSERS = /^(?:ال)?(?:بنطال|بنطلون|بناطيل|جينز)/u;
export function fixTrouserLength(text, name) {
  if (!TROUSERS.test(String(name || "").trim())) return String(text || "");
  return String(text || "")
    .replace(/(?<!\p{L})(?:ب)?(?:تصميم|قصّة|قصة)[ \t]+ماكسي(?!\p{L})/gu, "بطول كامل")
    .replace(/(?<!\p{L})ماكسي(?!\p{L})/gu, "بطول كامل");
}

// دعوة بيع لا تصف القطعة: «تسوقي الآن للحصول على…» (فستان 2026-09-12 02:27).
// بلهجة (حالات صناعية 2026-09-13): «احجزيها»، «خذيها قبل تخلص»، «الحقي بطلبك»، «اطلبه الحين»، «تبين تطلبين؟ كلمينا».
export const SALES_CTA = /(?<!\p{L})(?:تسوقي|تسوّقي|اطلبي|اطلبيها|اطلبه|اطلبها|احصلي|سارعي|اقتنيها|احجزيها|احجزي|احجزه|خذيها|خذيه|الحقي|كلمينا|كلمنا|راسلينا|لا تفوتي|(?:تبين|تبغين)[ \t]+تطلبين)(?!\p{L})/u;
// يُحذف مقطع الدعوة لا الجملة كلها: «تنورة ميدي بلسر بكسرات أمامية، خذيها قبل تخلص!» ⇒ «…بكسرات أمامية.»
export function dropSalesCta(text) {
  return joinSentences(splitSentencesKeep(text).map(({ s, p }) => ({ p, s: dropClauses(s, (c) => SALES_CTA.test(c)) })));
}
// «هذا القطع/القطعة» (بنطلون 2026-09-12 02:28)، و«إطلالة عملية في آنٍ واحد» بعد حذف «أنيقة و».
export function fixCommonGrammar(text) {
  return String(text || "")
    // فستان 2026-09-14 02:30: «مناسب للمناسبات اليومية» تناقض (المناسبة ليست يومية) ⇒ «للاستخدام اليومي».
    .replace(/(?<!\p{L})(مناسب(?:ة|ه)?|تناسب|يناسب)[ \t]+(?:لل|في[ \t]+ال)مناسبات[ \t]+اليومية(?!\p{L})/gu, "$1 للاستخدام اليومي")
    // «ويمكن ارتداؤه في مختلف الأوقات» حشو لا يصف القطعة.
    .replace(/[ \t]*[،,]?[ \t]*(?<!\p{L})(?:و)?(?:يمكن|تقدرين|تقدر)[ \t]+(?:ارتداؤه|ارتداؤها|ارتداءه|ارتداءها|لبسه|لبسها)[ \t]+(?:في|ب)[ \t]*(?:مختلف|كل|جميع)[ \t]+(?:ال)?(?:أوقات|اوقات|مناسبات|فعاليات)(?:[ \t]+(?:غير[ \t]+)?ال\p{L}+)?(?!\p{L})/gu, "")
    // «فستان أخضر فاتح بقصّة A للبيع.» (فستان 2026-09-14 03:26): «للبيع» حشو بالميتا والعنوان.
    .replace(/[ \t]+للبيع(?!\p{L})/gu, "")
    // «يمكن تنسيقه مع قطعة من الإكسسوارات بسيطة» — تنسيق عام بلا قطعة مسمّاة، وصياغته مكسورة: الجملة كلها.
    .replace(/(?<=^|[.!؟\n])[ \t]*(?:و)?(?:يمكن|تقدرين|تقدر)[ \t]+تنسيق(?:ه|ها)[ \t]+مع[ \t]+(?:قطعة|قطع)[ \t]+(?:من[ \t]+)?(?:ال)?(?:إكسسوارات|اكسسوارات)[^.!؟\n]*[.!؟]?/gu, "")
    // «متوفر الآن!» استعجال بالميتا والنبذة (معيار F8).
    .replace(/[ \t]*[،,]?[ \t]*(?<!\p{L})متوفر(?:ة|ه)?[ \t]+(?:الآن|الان|حالياً|حاليا)[ \t]*!*/gu, "")
    // بتر جملة بعد حذف حكم: «…وكسرات عريضة، ما.» ⇒ «…وكسرات عريضة.»
    .replace(/[ \t]*[،,][ \t]*(?:ما|مما|ما[ \t]+يمنح(?:ه|ها)?)[ \t]*([.!؟])/gu, "$1")
    .replace(/(?<!\p{L})هذا[ \t]+(?:القطعة|القطع)(?!\p{L})/gu, "هذه القطعة")
    // «بطبعة بايستيل» من ملاحظات Groq (جاكيت 2026-09-12 02:35): اسم الطبعة «بيزلي».
    .replace(/(?<!\p{L})بايستيل(?!\p{L})/gu, "بيزلي")
    // «وياقة دائرية وأكمام بلا أكمام» (جواب سؤال، nexos 2026-09-13): قيمة «بلا أكمام» أُلصقت بعنوانها.
    .replace(/(?<!\p{L})(و)?ب?أكمام[ \t]+(بلا|بدون)[ \t]+أكمام(?!\p{L})/gu, "$1$2 أكمام")
    // «ياقة مكشوفة الكتفين مع بلا أكمام» (جولة الجاهزية 2026-09-13).
    .replace(/(?<!\p{L})مع[ \t]+(بلا|بدون)(?!\p{L})/gu, "و$1")
    // كلمات مشوّهة بلا معنى من مخرجات حقيقية: «بسوار مضفر وسيعتا الحلقات»، «بحلقات مطاوير»، «أنيقة وستثنينية».
    .replace(/[ \t]*(?<!\p{L})(?:وسيعتا|مطاوير|وستثنينية)(?!\p{L})/gu, "")
    // «المناسبات اليومية والغير رسمية» ⇒ «وغير الرسمية» — كان بالنثر وحده ونجا بالنقاط (2026-09-13).
    .replace(/(?<!\p{L})(و)?ال(غير)[ \t]+(?!ال)(\p{L}+)/gu, "$1$2 ال$3")
    .replace(/(?<!\p{L})((?:ل|ب)?(?:إطلالة|اطلالة))[ \t]+(\p{L}+)[ \t]+في[ \t]+آن[ٍ]?[ \t]+واحد(?!\p{L})/gu, "$1 $2");
}

// مطابقة لون مؤنث بعد اسم قطعة نكرة مؤنثة: «تنورة فضي» ⇒ «تنورة فضية» (2026-09-12 02:34).
// «بلون فضي» صحيحة (اللون مذكر) فلا تُمس، ولا المعرّف («التنورة») تجنباً لـ«التنورة فضية».
// 2026-09-13: «شنطة أسود»، «عباية متعدد الألوان»، «تنورة بني» — قطع وألوان ناقصة.
const FEMININE_ITEM = "(?:تنورة|بلوزة|عباية|سترة|كنزة|بدلة|شنطة|حقيبة|جلابية|ساعة|نظارة|قلادة|جزمة|طرحة|شيلة)";
const COLOR_FEMININE = { "أسود": "سوداء", "اسود": "سوداء", "أبيض": "بيضاء", "ابيض": "بيضاء", "أحمر": "حمراء", "احمر": "حمراء", "أخضر": "خضراء", "اخضر": "خضراء", "أزرق": "زرقاء", "ازرق": "زرقاء", "أصفر": "صفراء", "اصفر": "صفراء", "فضي": "فضية", "ذهبي": "ذهبية", "وردي": "وردية", "زيتوني": "زيتونية", "زيتي": "زيتية", "كحلي": "كحلية", "رمادي": "رمادية", "بنفسجي": "بنفسجية", "برتقالي": "برتقالية", "عنابي": "عنابية", "خمري": "خمرية", "نيلي": "نيلية", "سماوي": "سماوية", "عسلي": "عسلية", "موفي": "موفية", "فوشي": "فوشية", "بني": "بنية", "تركوازي": "تركوازية", "زهري": "زهرية", "فيروزي": "فيروزية", "متعدد": "متعددة" };
const MASC_COLORS = Object.keys(COLOR_FEMININE).filter((k) => k !== "متعدد");
const COLOR_ALT = [...MASC_COLORS, "متعدد(?=[ \\t]+ال[أا]لوان)"].join("|");
const AGREEMENT = new RegExp(`(?<!\\p{L})((?:و|ب|ل)?${FEMININE_ITEM})[ \\t]+(${COLOR_ALT})(?!\\p{L})`, "gu");
// لون ثانٍ معطوف: «تنورة سوداء وأبيض» ⇒ «تنورة سوداء وبيضاء». اللون الأول المؤنث دليل التأنيث وحده:
// «تنورة ميدي سوداء وأبيض» (2026-09-13) كانت تفلت لأن «ميدي» تفصل القطعة عن اللون.
const CONJOINED = new RegExp(`(?<!\\p{L})((?:${[...new Set(Object.values(COLOR_FEMININE))].join("|")})[ \\t]+و)(${MASC_COLORS.join("|")})(?!\\p{L})`, "gu");
export function findColorAgreement(text) {
  const t = String(text || "");
  return [...t.matchAll(AGREEMENT), ...t.matchAll(CONJOINED)].map((m) => ({ wrong: `${m[1]} ${m[2]}`.replace(/و /, "و"), right: `${m[1]} ${COLOR_FEMININE[m[2]]}`.replace(/و /, "و") }));
}
export function fixColorAgreement(text) {
  return String(text || "").replace(AGREEMENT, (_m, item, color) => `${item} ${COLOR_FEMININE[color]}`)
    .replace(CONJOINED, (_m, head, color) => `${head}${COLOR_FEMININE[color]}`);
}
